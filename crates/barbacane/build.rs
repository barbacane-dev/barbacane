//! Generates the `barbacane control` commands from the control plane's
//! OpenAPI spec (`control-openapi.yaml`, a link to
//! `crates/barbacane-control/openapi.yaml`): one command per operation, its
//! parameters as flags. Requests and responses stay JSON; no types are
//! generated.
//!
//! An operation can set `x-cli` to `{ name, resource }` to rename its
//! command, or to `{ skip: true }` to have none.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use serde_json::Value;

#[path = "src/control/naming.rs"]
#[allow(dead_code)]
mod naming;

const SPEC: &str = "control-openapi.yaml";
const METHODS: [&str; 5] = ["get", "post", "put", "patch", "delete"];

struct Op {
    resource: String,
    words: Vec<String>,
    name_override: Option<String>,
    scoped_to_project: bool,
    method: String,
    path: String,
    summary: String,
    params: Vec<(String, String, bool, bool, String)>, // name, flag, in_path, required, help
    body: String,
    raw_response: bool,
}

fn main() {
    println!("cargo:rerun-if-changed={SPEC}");
    println!("cargo:rerun-if-changed=src/control/naming.rs");
    let text = std::fs::read_to_string(SPEC).expect("read control-openapi.yaml");
    let spec: Value = serde_saphyr::from_str(&text).expect("control-openapi.yaml parses");

    let mut ops = Vec::new();
    for (path, item) in spec["paths"].as_object().expect("paths") {
        for method in METHODS {
            let Some(op) = item.get(method) else { continue };
            let cli = &op["x-cli"];
            if cli["skip"].as_bool() == Some(true) {
                continue;
            }
            let tag = op["tags"][0].as_str().expect("one tag per operation");
            let id = op["operationId"].as_str().expect("operationId");
            let params = parameters(&spec, item, op);
            let scoped_to_project = params.iter().any(|p| p.0 == "projectId");
            ops.push(Op {
                resource: cli["resource"]
                    .as_str()
                    .map(str::to_string)
                    .unwrap_or_else(|| naming::resource(tag)),
                words: naming::name_words(tag, id),
                name_override: cli["name"].as_str().map(str::to_string),
                scoped_to_project,
                method: method.to_uppercase(),
                path: path.clone(),
                summary: op["summary"].as_str().unwrap_or(id).to_string(),
                params,
                body: body(&spec, op),
                raw_response: raw_response(op),
            });
        }
    }

    // `project` is dropped from a project-scoped name when the shorter name
    // stays unique within its resource: `api-keys list`, but `specs
    // list-project` beside `specs list`.
    let short = |op: &Op| -> String {
        let kept: Vec<&str> = op
            .words
            .iter()
            .map(String::as_str)
            .filter(|w| *w != "project")
            .collect();
        kept.join("-")
    };
    let mut names = Vec::new();
    for op in &ops {
        let name = op.name_override.clone().unwrap_or_else(|| {
            let shorter = short(op);
            let clashes = ops.iter().any(|other| {
                !std::ptr::eq(other, op)
                    && other.resource == op.resource
                    && (other.words.join("-") == shorter || short(other) == shorter)
            });
            if op.scoped_to_project && !shorter.is_empty() && !clashes {
                shorter
            } else {
                op.words.join("-")
            }
        });
        names.push(name);
    }

    let mut seen = BTreeSet::new();
    for (op, name) in ops.iter().zip(&names) {
        assert!(
            seen.insert((op.resource.clone(), name.clone())),
            "two operations would be `{} {}`; set x-cli on one",
            op.resource,
            name
        );
    }

    let mut out = String::from(
        "// Generated by build.rs from control-openapi.yaml. Do not edit.\n\n/// One command per operation of the control-plane API.\npub static OPERATIONS: &[Operation] = &[\n",
    );
    for (op, name) in ops.iter().zip(&names) {
        let mut params = String::new();
        for (pname, flag, in_path, required, help) in &op.params {
            let location = if *in_path {
                "Location::Path"
            } else {
                "Location::Query"
            };
            let _ = write!(
                params,
                "Param {{ name: {pname:?}, flag: {flag:?}, location: {location}, required: {required}, help: {help:?} }}, "
            );
        }
        let _ = writeln!(
            out,
            "    Operation {{ resource: {:?}, name: {:?}, method: {:?}, path: {:?}, summary: {:?}, params: &[{params}], body: {}, raw_response: {} }},",
            op.resource, name, op.method, op.path, op.summary, op.body, op.raw_response
        );
    }
    out.push_str("];\n\n/// Each resource's description, from the spec's tags.\npub static RESOURCES: &[(&str, &str)] = &[\n");
    for tag in spec["tags"].as_array().into_iter().flatten() {
        let name = tag["name"].as_str().expect("tag name");
        let _ = writeln!(
            out,
            "    ({:?}, {:?}),",
            naming::resource(name),
            one_line(tag["description"].as_str().unwrap_or(name))
        );
    }
    out.push_str("];\n");
    let dest =
        std::path::Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("control_api.rs");
    std::fs::write(dest, out).expect("write control_api.rs");
}

/// Path and query parameters, the path item's and the operation's, with
/// references resolved.
fn parameters(spec: &Value, item: &Value, op: &Value) -> Vec<(String, String, bool, bool, String)> {
    let mut found = Vec::new();
    let lists = [item["parameters"].as_array(), op["parameters"].as_array()];
    for param in lists.into_iter().flatten().flatten() {
        let param = resolve(spec, param);
        let location = param["in"].as_str().unwrap_or_default();
        if location != "path" && location != "query" {
            continue;
        }
        let name = param["name"].as_str().expect("parameter name").to_string();
        let in_path = location == "path";
        found.push((
            name.clone(),
            naming::flag(&name),
            in_path,
            in_path || param["required"].as_bool() == Some(true),
            one_line(param["description"].as_str().unwrap_or_default()),
        ));
    }
    found
}

/// The `Body` value an operation's request body maps to.
fn body(spec: &Value, op: &Value) -> String {
    let Some(request) = op.get("requestBody") else {
        return "Body::None".to_string();
    };
    let required = request["required"].as_bool() == Some(true);
    let content = &request["content"];
    if let Some(form) = content.get("multipart/form-data") {
        let schema = resolve(spec, &form["schema"]);
        let required_fields: Vec<&str> = schema["required"]
            .as_array()
            .map(|r| r.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let mut fields = String::new();
        for (name, field) in schema["properties"].as_object().into_iter().flatten() {
            let _ = write!(
                fields,
                "Field {{ name: {name:?}, flag: {:?}, file: {}, required: {}, help: {:?} }}, ",
                naming::flag(name),
                field["format"].as_str() == Some("binary"),
                required_fields.contains(&name.as_str()),
                one_line(field["description"].as_str().unwrap_or_default()),
            );
        }
        return format!("Body::Multipart(&[{fields}])");
    }
    format!("Body::Json {{ required: {required} }}")
}

/// Whether the success response is something other than JSON (a download).
fn raw_response(op: &Value) -> bool {
    let responses = op["responses"].as_object().into_iter().flatten();
    responses
        .filter(|(status, _)| status.starts_with('2'))
        .filter_map(|(_, r)| r["content"].as_object())
        .any(|content| !content.keys().any(|m| m.contains("json")))
}

fn resolve<'a>(spec: &'a Value, value: &'a Value) -> &'a Value {
    match value["$ref"].as_str() {
        Some(reference) => {
            let mut target = spec;
            for part in reference.trim_start_matches("#/").split('/') {
                target = &target[part];
            }
            target
        }
        None => value,
    }
}

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}
